'use strict';
// System tray icon + menu, and the unread badge on the taskbar button (Windows), dock (macOS) and launcher (Linux).
const { app, Menu, Tray, nativeImage } = require('electron');
const path = require('node:path');

const ASSETS = path.join(__dirname, 'assets');
const isMac = process.platform === 'darwin';
const isWin = process.platform === 'win32';

// nativeImage picks up the matching @2x file automatically for HiDPI screens.
const image = (file) => nativeImage.createFromPath(path.join(ASSETS, file));

// Taskbar overlay badges come from one sprite sheet per display scale (generated by brand/export.mjs):
// cells "1" … "99" then "99+", row 0 = unread (red), row 1 = notifications paused (gray).
const BADGE_SCALES = [
  [16, 1],
  [20, 1.25],
  [24, 1.5],
  [32, 2],
];
const BADGE_CELLS = 100;
let sprites = null;
const badgeCache = new Map();

/** "7", "42", "99+" — the label a count shows on the badge. */
const badgeLabel = (count) => (count > 99 ? '99+' : String(count));

/** Overlay image for a count, with a representation for every display scale so it stays sharp on HiDPI screens. */
function badgeImage(count, paused) {
  const cell = Math.min(count, BADGE_CELLS) - 1;
  const key = `${cell}:${paused ? 1 : 0}`;
  if (badgeCache.has(key)) return badgeCache.get(key);
  sprites ??= new Map(BADGE_SCALES.map(([size]) => [size, image(path.join('badges', `badge-sprite-${size}.png`))]));
  const img = nativeImage.createEmpty();
  for (const [size, scaleFactor] of BADGE_SCALES) {
    const sheet = sprites.get(size);
    if (!sheet || sheet.isEmpty()) continue;
    const part = sheet.crop({ x: cell * size, y: paused ? size : 0, width: size, height: size });
    img.addRepresentation({ scaleFactor, buffer: part.toPNG() });
  }
  badgeCache.set(key, img);
  return img;
}

const fmtTime = (ms) => new Date(ms).toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' });

function tomorrowMorning() {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  d.setHours(8, 0, 0, 0);
  return d.getTime();
}

/**
 * @param {{
 *   getWindow: () => Electron.BrowserWindow | null,
 *   showWindow: () => void,
 *   markAllRead: () => void,
 *   changeServer: () => void,
 *   setDnd: (until: number) => void,
 *   getDnd: () => number,
 *   settings: { get: (k: string) => any, set: (p: object) => void },
 *   quit: () => void,
 * }} deps
 */
function createTray(deps) {
  const icons = { normal: image('tray.png'), unread: image('tray-unread.png'), muted: image('tray-muted.png') };
  const tray = new Tray(icons.normal);
  let unread = 0;

  const tooltip = () => {
    const paused = deps.getDnd() > Date.now();
    const parts = ['Slack Analyze'];
    if (unread) parts.push(`${unread} unread message${unread === 1 ? '' : 's'}`);
    if (paused) parts.push(`notifications paused until ${fmtTime(deps.getDnd())}`);
    return parts.join(' — ');
  };

  const pauseItem = (label, ms) => ({ label, click: () => deps.setDnd(ms()) });

  function buildMenu() {
    const dnd = deps.getDnd();
    const paused = dnd > Date.now();
    const login = app.isPackaged ? app.getLoginItemSettings({ args: ['--hidden'] }) : null;
    return Menu.buildFromTemplate([
      { label: 'Open Slack Analyze', click: deps.showWindow },
      { type: 'separator' },
      { label: unread ? `${unread} unread message${unread === 1 ? '' : 's'}` : 'No unread messages', enabled: false },
      { label: 'Mark all as read', enabled: unread > 0, click: deps.markAllRead },
      { type: 'separator' },
      paused
        ? { label: `Notifications paused until ${fmtTime(dnd)}`, enabled: false }
        : { label: 'Notifications on', enabled: false },
      paused
        ? { label: 'Resume notifications', click: () => deps.setDnd(0) }
        : {
            label: 'Pause notifications',
            submenu: [
              pauseItem('For 30 minutes', () => Date.now() + 30 * 60_000),
              pauseItem('For 1 hour', () => Date.now() + 60 * 60_000),
              pauseItem('For 2 hours', () => Date.now() + 2 * 60 * 60_000),
              pauseItem('Until tomorrow (8:00)', tomorrowMorning),
            ],
          },
      { type: 'separator' },
      {
        label: 'Settings',
        submenu: [
          {
            label: 'Open at login',
            type: 'checkbox',
            enabled: Boolean(login),
            checked: Boolean(login?.openAtLogin),
            click: (item) => {
              app.setLoginItemSettings({ openAtLogin: item.checked, openAsHidden: true, args: ['--hidden'] });
              refresh();
            },
          },
          {
            label: 'Keep running in the tray when closed',
            type: 'checkbox',
            checked: deps.settings.get('closeToTray'),
            click: (item) => deps.settings.set({ closeToTray: item.checked }),
          },
          {
            label: isWin ? 'Flash the taskbar button on new messages' : 'Bounce the dock icon on new messages',
            type: 'checkbox',
            checked: deps.settings.get('flashFrame'),
            click: (item) => deps.settings.set({ flashFrame: item.checked }),
          },
          { type: 'separator' },
          { label: 'Change server…', click: deps.changeServer },
        ],
      },
      { type: 'separator' },
      { label: 'Quit Slack Analyze', click: deps.quit },
    ]);
  }

  function refresh() {
    tray.setToolTip(tooltip());
    tray.setContextMenu(buildMenu());
  }

  // Left click opens the app (Windows / Linux); the context menu stays on right click. macOS shows the menu on click.
  if (!isMac) tray.on('click', deps.showWindow);
  tray.on('double-click', deps.showWindow);

  let shown = null; // "<count>:<paused>" currently on screen, so repeated updates are free

  /**
   * Unread count on the taskbar button (Windows overlay), dock (macOS) or launcher (Linux), the tray icon and its menu.
   * Exact up to 99, then "99+"; gray instead of red while notifications are paused.
   */
  function setUnread(count, force = false) {
    unread = Math.max(0, Math.min(Number.isFinite(count) ? Math.floor(count) : 0, 99999));
    const paused = deps.getDnd() > Date.now();
    const key = `${unread}:${paused}`;
    if (key === shown && !force) return;
    shown = key;

    tray.setImage(!unread ? icons.normal : paused ? icons.muted : icons.unread);
    const win = deps.getWindow();
    if (isWin && win && !win.isDestroyed()) {
      // Screen readers announce the description with the taskbar button.
      const description = unread ? `${unread} unread message${unread === 1 ? '' : 's'}${paused ? ', notifications paused' : ''}` : '';
      win.setOverlayIcon(unread ? badgeImage(unread, paused) : null, description);
    } else if (isMac) {
      app.dock?.setBadge(unread ? badgeLabel(unread) : '');
    } else {
      app.setBadgeCount(unread);
    }
    refresh();
  }

  /** Re-applies the badge: after the window is shown again (Windows drops overlays of hidden windows) or a pause change. */
  function reapply() {
    setUnread(unread, true);
  }

  refresh();
  return {
    tray,
    setUnread,
    reapply,
    refresh,
    getUnread: () => unread,
    displayBalloon: (title, content) => {
      if (isWin) tray.displayBalloon({ title, content, iconType: 'custom', icon: image('icon.png'), respectQuietTime: true });
    },
  };
}

module.exports = { createTray, badgeImage, badgeLabel };
